/** Icons a user can pick for a metric or dashboard. */
export const METRIC_ICONS: Record<string, LucideIcon> = {
  scale: Scale,
  ruler: Ruler,
  heart: Heart,
  activity: Activity,
  footprints: Footprints,
  dumbbell: Dumbbell,
  bike: Bike,
  mountain: Mountain,
  flame: Flame,
  droplet: Droplet,
  apple: Apple,
  coffee: Coffee,
  wine: Wine,
  moon: Moon,
  bed: Bed,
  sun: Sun,
  smile: Smile,
  brain: Brain,
  thermometer: Thermometer,
  timer: Timer,
  'book-open': BookOpen,
  music: Music,
  wallet: Wallet,
  banknote: Banknote,
  'piggy-bank': PiggyBank,
  'circle-dollar-sign': CircleDollarSign,
  'trending-up': TrendingUp,
  receipt: Receipt,
  home: Home,
  target: Target,
  gauge: Gauge,
  trophy: Trophy,
  zap: Zap,
  calendar: Calendar,
  sparkles: Sparkles,
};

export function MetricIcon({ name, size = 18 }: { name?: string | null; size?: number }) {
  const I = (name && METRIC_ICONS[name]) || Sparkles;
  return <I size={size} strokeWidth={2} aria-hidden />;
}
